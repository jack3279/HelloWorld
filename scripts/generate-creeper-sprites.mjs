// Generates the side-view creeper walk kit:
//   assets/creeper-walk.svg             mid-stride still
//   assets/creeper-sprites/walk-N.svg   one frame per pose
//
// Usage:
//   node scripts/generate-creeper-sprites.mjs [--skin=<png>] [--out=<dir>]
import { mkdir, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { buildFigure, loadCreeperSkin, makeProjector, parseArgs, svgFigureBody } from "./lib/steve-model.mjs";
import { CREEPER_MODEL } from "./lib/creeper-model.mjs";
import { SPRITE, TOLERANCE, catalog } from "./lib/creeper-poses.mjs";

const __dirname = dirname(fileURLToPath(import.meta.url));

const project = makeProjector({
  scale: SPRITE.scale,
  originX: SPRITE.originX,
  originY: SPRITE.originY,
});

function frameSvg(id, label, parts) {
  return `<!-- Generated by scripts/generate-creeper-sprites.mjs -->
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${SPRITE.w} ${SPRITE.h}" width="${SPRITE.w}" height="${SPRITE.h}" role="img" aria-labelledby="${id}-title">
  <title id="${id}-title">${label}</title>
  <g id="creeper">
${svgFigureBody(parts, project).join("\n")}
  </g>
</svg>
`;
}

const args = parseArgs(process.argv.slice(2));
const skin = await loadCreeperSkin(args.get("skin"));
if (skin.width < 64 || skin.height < 32) throw new Error("expected a 64x32 creeper texture");

const outDir = resolve(__dirname, "..", args.get("out") ?? "assets/creeper-sprites");
await mkdir(outDir, { recursive: true });

const frames = [];
for (const entry of catalog()) {
  const { parts } = buildFigure({ skin, pose: entry.pose, tolerance: TOLERANCE, model: CREEPER_MODEL });
  const svg = frameSvg(entry.id, entry.label, parts);
  await writeFile(resolve(outDir, `${entry.id}.svg`), svg);
  frames.push({ ...entry, parts, bytes: svg.length });
}

const mid = frames[Math.floor(frames.length / 4)];
const walkStill = resolve(__dirname, "../assets/creeper-walk.svg");
await writeFile(
  walkStill,
  frameSvg("creeper-walk", "Creeper, walking, facing right", mid.parts).replace(
    "generate-creeper-sprites.mjs",
    "generate-creeper-sprites.mjs (walk-4)",
  ),
);

console.log(
  `Wrote ${frames.length} walk frames in ${outDir} (${(frames.reduce((n, f) => n + f.bytes, 0) / 1024).toFixed(1)} kB)`,
);
console.log(`Wrote ${walkStill}`);
