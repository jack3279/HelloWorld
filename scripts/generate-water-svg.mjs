// Generates the still-water square and a seamless floor of the same tile:
//   assets/water-side.svg              first frame, one square
//   assets/water-tiles.svg             3×3 floor, same frame, no gaps
//   assets/water-sprites/still-N.svg   one frame of the official still-water strip
//
// Usage:
//   node scripts/generate-water-svg.mjs [--skin=<png>]
import { mkdir, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import {
  FLOOR,
  SINGLE,
  frameCount,
  layoutFloor,
  layoutSingle,
  loadWaterStrip,
  parseArgs,
  runsOf,
  runsOfTiled,
  svgFromRuns,
} from "./lib/water-block.mjs";

const __dirname = dirname(fileURLToPath(import.meta.url));

function wrapSvg(id, label, canvas, body) {
  return `<!-- Generated by scripts/generate-water-svg.mjs -->
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${canvas.w} ${canvas.h}" width="${canvas.w}" height="${canvas.h}" role="img" aria-labelledby="${id}-title">
  <title id="${id}-title">${label}</title>
  ${body}
</svg>
`;
}

const args = parseArgs(process.argv.slice(2));
const strip = await loadWaterStrip(args.get("skin"));
const n = frameCount(strip);
const outDir = resolve(__dirname, "../assets/water-sprites");
await mkdir(outDir, { recursive: true });

const singleBox = layoutSingle();
const first = runsOf(strip, 0);
const side = resolve(__dirname, "../assets/water-side.svg");
await writeFile(
  side,
  wrapSvg(
    "water-side",
    "Water block, square face",
    SINGLE,
    `<g id="water-block">\n    ${svgFromRuns(first, singleBox).join("\n    ")}\n  </g>`,
  ),
);

const floor = layoutFloor();
const tiled = resolve(__dirname, "../assets/water-tiles.svg");
await writeFile(
  tiled,
  wrapSvg(
    "water-tiles",
    "Water floor, 3 by 3 seamless tiles",
    FLOOR,
    `<g id="water-floor">\n    ${svgFromRuns(runsOfTiled(strip, 0, floor.cols, floor.rows), floor).join("\n    ")}\n  </g>`,
  ),
);

for (let i = 0; i < n; i++) {
  const svg = wrapSvg(
    `still-${i}`,
    `Water still ${i + 1}/${n}`,
    SINGLE,
    `<g id="water-block">\n    ${svgFromRuns(runsOf(strip, i), singleBox).join("\n    ")}\n  </g>`,
  );
  await writeFile(resolve(outDir, `still-${i}.svg`), svg);
}

console.log(`Wrote ${side}`);
console.log(`Wrote ${tiled}`);
console.log(`Wrote ${n} still frames in ${outDir}`);
