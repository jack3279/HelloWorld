// Generates the flowing water kit from the official still-water strip:
//   assets/water-side.svg
//   assets/water-sprites/flow-N.svg
//
// Usage:
//   node scripts/generate-water-svg.mjs [--skin=<png>]
import { mkdir, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { CANVAS, frameCount, layout, loadWaterStrip, parseArgs, runsOf, svgFromRuns } from "./lib/water-block.mjs";

const __dirname = dirname(fileURLToPath(import.meta.url));

function frameSvg(id, label, runs) {
  const box = layout();
  return `<!-- Generated by scripts/generate-water-svg.mjs -->
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${CANVAS.w} ${CANVAS.h}" width="${CANVAS.w}" height="${CANVAS.h}" role="img" aria-labelledby="${id}-title">
  <title id="${id}-title">${label}</title>
  <g id="water-block">
    ${svgFromRuns(runs, box).join("\n    ")}
  </g>
</svg>
`;
}

const args = parseArgs(process.argv.slice(2));
const strip = await loadWaterStrip(args.get("skin"));
const n = frameCount(strip);
const outDir = resolve(__dirname, "../assets/water-sprites");
await mkdir(outDir, { recursive: true });

const first = runsOf(strip, 0);
await writeFile(resolve(__dirname, "../assets/water-side.svg"), frameSvg("water-side", "Water block, side view", first));

for (let i = 0; i < n; i++) {
  const svg = frameSvg(`flow-${i}`, `Water flow ${i + 1}/${n}`, runsOf(strip, i));
  await writeFile(resolve(outDir, `flow-${i}.svg`), svg);
}

console.log(`Wrote ${n} water flow frames in ${outDir}`);
