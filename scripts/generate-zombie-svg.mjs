// Generates assets/zombie-side.svg: a right-facing Minecraft zombie.
// The body stays in true profile; the head turns 45° toward the camera so
// both eye sockets and the mouth read on the front of the cube.
//
// Usage:
//   node scripts/generate-zombie-svg.mjs [--skin=<png>] [--out=<svg>]
import { mkdir, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { buildFigure, fitProjector, loadZombieSkin, parseArgs, svgFigureBody } from "./lib/steve-model.mjs";
import { idleA, TOLERANCE } from "./lib/zombie-poses.mjs";

const __dirname = dirname(fileURLToPath(import.meta.url));

const CANVAS = { w: 512, h: 520, pad: 18 };

const args = parseArgs(process.argv.slice(2));
const skin = await loadZombieSkin(args.get("skin"));
if (skin.width < 64 || skin.height < 64) throw new Error("expected a 64x64 skin");

const pose = idleA();
const { parts, palette } = buildFigure({ skin, pose, tolerance: TOLERANCE });
const project = fitProjector(parts, CANVAS, pose.roll ?? 0);
const svg = `<!-- Generated by scripts/generate-zombie-svg.mjs — edit the pose in lib/zombie-poses.mjs, not here. -->
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${CANVAS.w} ${CANVAS.h}" width="${CANVAS.w}" height="${CANVAS.h}" role="img" aria-labelledby="zombie-title zombie-desc">
  <title id="zombie-title">Zombie, side view</title>
  <desc id="zombie-desc">Voxel zombie facing right with the head turned 45 degrees so the face — both eye sockets and the mouth — stays readable.</desc>
  <g id="zombie">
${svgFigureBody(parts, project).join("\n")}
  </g>
</svg>
`;

const out = resolve(__dirname, "..", args.get("out") ?? "assets/zombie-side.svg");
await mkdir(dirname(out), { recursive: true });
await writeFile(out, svg);
console.log(
  `Wrote ${out} (${(svg.length / 1024).toFixed(1)} kB, ${palette.size} flat colors, ` +
    `${parts.reduce((n, p) => n + p.faces.length, 0)} visible faces)`,
);
