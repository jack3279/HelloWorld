// Generates the side-view platformer kit:
//   assets/steve-side.svg              idle hero, facing right
//   assets/steve-sprites/<id>.svg      one frame per pose
//   assets/steve-sprites/sheet.svg     all frames in a grid
//   assets/steve-sprites/atlas.json    frame rects, anchors, animation lists
//
// Usage:
//   node scripts/generate-steve-sprites.mjs [--skin=<png>] [--out=<dir>]
import { mkdir, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { buildFigure, loadSkin, makeProjector, parseArgs, svgFigureBody } from "./lib/steve-model.mjs";
import { ANIMATIONS, SPRITE, TOLERANCE, catalog } from "./lib/steve-poses.mjs";

const __dirname = dirname(fileURLToPath(import.meta.url));

const project = makeProjector({
  scale: SPRITE.scale,
  originX: SPRITE.originX,
  originY: SPRITE.originY,
});

function frameSvg(id, label, parts) {
  return `<!-- Generated by scripts/generate-steve-sprites.mjs -->
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${SPRITE.w} ${SPRITE.h}" width="${SPRITE.w}" height="${SPRITE.h}" role="img" aria-labelledby="${id}-title">
  <title id="${id}-title">${label}</title>
  <g id="steve">
${svgFigureBody(parts, project).join("\n")}
  </g>
</svg>
`;
}

const args = parseArgs(process.argv.slice(2));
const skin = await loadSkin(args.get("skin"));
if (skin.width < 64 || skin.height < 64) throw new Error("expected a 64x64 skin");

const outDir = resolve(__dirname, "..", args.get("out") ?? "assets/steve-sprites");
await mkdir(outDir, { recursive: true });

const frames = [];
for (const entry of catalog()) {
  const { parts } = buildFigure({ skin, pose: entry.pose, tolerance: TOLERANCE });
  const svg = frameSvg(entry.id, entry.label, parts);
  const file = `${entry.id}.svg`;
  await writeFile(resolve(outDir, file), svg);
  frames.push({ ...entry, file, parts, bytes: svg.length });
}

const side = frames.find((f) => f.id === "idle-a");
const sidePath = resolve(__dirname, "../assets/steve-side.svg");
await mkdir(dirname(sidePath), { recursive: true });
await writeFile(
  sidePath,
  frameSvg("steve-side", "Steve, side view, facing right", side.parts).replace(
    "generate-steve-sprites.mjs",
    "generate-steve-sprites.mjs (idle-a)",
  ),
);

const COLS = 8;
const ROWS = Math.ceil(frames.length / COLS);
const sheetW = COLS * SPRITE.w;
const sheetH = ROWS * SPRITE.h;
const cells = [];
const atlasFrames = {};
frames.forEach((frame, i) => {
  const col = i % COLS;
  const row = Math.floor(i / COLS);
  const x = col * SPRITE.w;
  const y = row * SPRITE.h;
  const cellProject = (p) => {
    const [sx, sy] = project(p);
    return [sx + x, sy + y];
  };
  cells.push(`  <g id="${frame.id}" transform="translate(${x} ${y})">`);
  cells.push(...svgFigureBody(frame.parts, project, "    ", `${frame.id}-`));
  cells.push("  </g>");
  atlasFrames[frame.id] = {
    file: frame.file,
    label: frame.label,
    tags: frame.tags,
    frame: { x, y, w: SPRITE.w, h: SPRITE.h },
    // Feet sit on this pixel so a game can pin the sprite to the ground.
    anchor: { x: SPRITE.originX, y: SPRITE.originY },
  };
  void cellProject;
});

const sheet = `<!-- Generated by scripts/generate-steve-sprites.mjs -->
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${sheetW} ${sheetH}" width="${sheetW}" height="${sheetH}" role="img" aria-label="Steve platformer sprite sheet">
${cells.join("\n")}
</svg>
`;
await writeFile(resolve(outDir, "sheet.svg"), sheet);

const atlas = {
  meta: {
    character: "steve",
    facing: "right",
    image: "sheet.svg",
    size: { w: sheetW, h: sheetH },
    tile: { w: SPRITE.w, h: SPRITE.h },
    scale: SPRITE.scale,
    generatedBy: "scripts/generate-steve-sprites.mjs",
  },
  frames: atlasFrames,
  animations: ANIMATIONS,
};
await writeFile(resolve(outDir, "atlas.json"), JSON.stringify(atlas, null, 2) + "\n");

const kb = (n) => (n / 1024).toFixed(1);
console.log(
  `Wrote ${frames.length} frames in ${outDir} (${kb(frames.reduce((n, f) => n + f.bytes, 0))} kB) plus sheet.svg and atlas.json`,
);
console.log(`Wrote ${sidePath}`);
