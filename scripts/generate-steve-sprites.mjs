// Generates the side-view platformer kit:
//   assets/steve-side.svg              idle hero, facing right
//   assets/steve-sprites/<id>.svg      one frame per pose
//   assets/steve-sprites/sheet.svg     idle / run / jump grid
//   assets/steve-sprites/combat-sheet.svg  sword / hurt / death row
//   assets/steve-sprites/atlas.json    frame rects, anchors, animation lists
//
// Usage:
//   node scripts/generate-steve-sprites.mjs [--skin=<png>] [--out=<dir>]
import { mkdir, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { buildFigure, loadSkin, makeProjector, parseArgs, svgFigureBody } from "./lib/steve-model.mjs";
import { ANIMATIONS, COMBAT_SPRITE, SPRITE, TOLERANCE, catalog } from "./lib/steve-poses.mjs";

const __dirname = dirname(fileURLToPath(import.meta.url));

function frameSvg(id, label, parts, canvas, project) {
  return `<!-- Generated by scripts/generate-steve-sprites.mjs -->
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${canvas.w} ${canvas.h}" width="${canvas.w}" height="${canvas.h}" role="img" aria-labelledby="${id}-title">
  <title id="${id}-title">${label}</title>
  <g id="steve">
${svgFigureBody(parts, project).join("\n")}
  </g>
</svg>
`;
}

function writeSheet(frames, canvas, label) {
  const COLS = frames[0]?.tags?.includes("combat") ? Math.min(frames.length, 10) : 8;
  const ROWS = Math.ceil(frames.length / COLS);
  const sheetW = COLS * canvas.w;
  const sheetH = ROWS * canvas.h;
  const cells = [];
  const atlasFrames = {};
  frames.forEach((frame, i) => {
    const col = i % COLS;
    const row = Math.floor(i / COLS);
    const x = col * canvas.w;
    const y = row * canvas.h;
    cells.push(`  <g id="${frame.id}" transform="translate(${x} ${y})">`);
    cells.push(...svgFigureBody(frame.parts, frame.project, "    ", `${frame.id}-`));
    cells.push("  </g>");
    atlasFrames[frame.id] = {
      file: frame.file,
      label: frame.label,
      tags: frame.tags,
      frame: { x, y, w: canvas.w, h: canvas.h },
      anchor: { x: canvas.originX, y: canvas.originY },
    };
  });
  const sheet = `<!-- Generated by scripts/generate-steve-sprites.mjs -->
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${sheetW} ${sheetH}" width="${sheetW}" height="${sheetH}" role="img" aria-label="${label}">
${cells.join("\n")}
</svg>
`;
  return { sheet, atlasFrames, size: { w: sheetW, h: sheetH } };
}

const args = parseArgs(process.argv.slice(2));
const skin = await loadSkin(args.get("skin"));
if (skin.width < 64 || skin.height < 64) throw new Error("expected a 64x64 skin");

const outDir = resolve(__dirname, "..", args.get("out") ?? "assets/steve-sprites");
await mkdir(outDir, { recursive: true });

const frames = [];
for (const entry of catalog()) {
  const combat = entry.tags.includes("combat");
  const canvas = combat ? COMBAT_SPRITE : SPRITE;
  const project = makeProjector({
    scale: canvas.scale,
    originX: canvas.originX,
    originY: canvas.originY,
    roll: entry.pose.roll ?? 0,
  });
  const { parts } = buildFigure({
    skin,
    pose: entry.pose,
    tolerance: TOLERANCE,
  });
  const svg = frameSvg(entry.id, entry.label, parts, canvas, project);
  const file = `${entry.id}.svg`;
  await writeFile(resolve(outDir, file), svg);
  frames.push({ ...entry, file, parts, project, bytes: svg.length, canvas });
}

const side = frames.find((f) => f.id === "idle-a");
const sidePath = resolve(__dirname, "../assets/steve-side.svg");
await mkdir(dirname(sidePath), { recursive: true });
const idleProject = makeProjector({
  scale: SPRITE.scale,
  originX: SPRITE.originX,
  originY: SPRITE.originY,
});
await writeFile(
  sidePath,
  frameSvg("steve-side", "Steve, side view, facing right", side.parts, SPRITE, idleProject).replace(
    "generate-steve-sprites.mjs",
    "generate-steve-sprites.mjs (idle-a)",
  ),
);

const loco = frames.filter((f) => !f.tags.includes("combat"));
const combat = frames.filter((f) => f.tags.includes("combat"));
const locoSheet = writeSheet(loco, SPRITE, "Steve platformer sprite sheet");
await writeFile(resolve(outDir, "sheet.svg"), locoSheet.sheet);

const combatSheet = writeSheet(combat, COMBAT_SPRITE, "Steve combat sprite sheet");
await writeFile(resolve(outDir, "combat-sheet.svg"), combatSheet.sheet);

const atlas = {
  meta: {
    character: "steve",
    facing: "right",
    image: "sheet.svg",
    combatImage: "combat-sheet.svg",
    size: locoSheet.size,
    combatSize: combatSheet.size,
    tile: { w: SPRITE.w, h: SPRITE.h },
    combatTile: { w: COMBAT_SPRITE.w, h: COMBAT_SPRITE.h },
    scale: SPRITE.scale,
    generatedBy: "scripts/generate-steve-sprites.mjs",
  },
  frames: { ...locoSheet.atlasFrames, ...combatSheet.atlasFrames },
  animations: ANIMATIONS,
};
await writeFile(resolve(outDir, "atlas.json"), JSON.stringify(atlas, null, 2) + "\n");

const kb = (n) => (n / 1024).toFixed(1);
console.log(
  `Wrote ${frames.length} frames in ${outDir} (${kb(frames.reduce((n, f) => n + f.bytes, 0))} kB) plus sheet.svg, combat-sheet.svg and atlas.json`,
);
console.log(`Wrote ${sidePath}`);
