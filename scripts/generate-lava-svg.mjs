// Generates the side-view lava block still and the boil frame kit:
//   assets/lava-side.svg              first frame, a square
//   assets/lava-sprites/boil-N.svg    one frame of the official still-lava strip
//
// Usage:
//   node scripts/generate-lava-svg.mjs [--skin=<png>]
import { mkdir, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import {
  CANVAS,
  frameCount,
  layout,
  loadLavaStrip,
  parseArgs,
  runsOf,
  svgFromRuns,
} from "./lib/lava-block.mjs";

const __dirname = dirname(fileURLToPath(import.meta.url));

function frameSvg(id, label, runs) {
  const box = layout();
  return `<!-- Generated by scripts/generate-lava-svg.mjs -->
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${CANVAS.w} ${CANVAS.h}" width="${CANVAS.w}" height="${CANVAS.h}" role="img" aria-labelledby="${id}-title">
  <title id="${id}-title">${label}</title>
  <g id="lava-block">
    ${svgFromRuns(runs, box).join("\n    ")}
  </g>
</svg>
`;
}

const args = parseArgs(process.argv.slice(2));
const strip = await loadLavaStrip(args.get("skin"));
const n = frameCount(strip);
const outDir = resolve(__dirname, "../assets/lava-sprites");
await mkdir(outDir, { recursive: true });

const first = runsOf(strip, 0);
const side = resolve(__dirname, "../assets/lava-side.svg");
await writeFile(side, frameSvg("lava-side", "Lava block, side view", first));

for (let i = 0; i < n; i++) {
  const svg = frameSvg(`boil-${i}`, `Lava boil ${i + 1}/${n}`, runsOf(strip, i));
  await writeFile(resolve(outDir, `boil-${i}.svg`), svg);
}

console.log(`Wrote ${side}`);
console.log(`Wrote ${n} boil frames in ${outDir}`);
