// Shared SVG / sprite-sheet / Skottie flipbook writer for posed cuboid mobs.
import { mkdir, readdir, rm, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { DEFAULT_SHADING, buildFigure, figureToLottieShapes, fitProjector, makeProjector, svgFigureBody } from "./steve-model.mjs";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "../..");

function shapeLayer({ ind, name, ip, op, shapes, opacity = 100 }) {
  return {
    ddd: 0,
    ind,
    ty: 4,
    nm: name,
    sr: 1,
    ks: {
      o: { a: 0, k: opacity },
      r: { a: 0, k: 0 },
      p: { a: 0, k: [0, 0, 0] },
      a: { a: 0, k: [0, 0, 0] },
      s: { a: 0, k: [100, 100, 100] },
    },
    ao: 0,
    shapes,
    ip,
    op,
    st: ip,
    bm: 0,
  };
}

export function flipbook({ name, w, h, frames, fps, hold, loop, generator }) {
  const op = frames.length * hold;
  const layers = frames.map((frame, i) =>
    shapeLayer({
      ind: frames.length - i,
      name: frame.id,
      ip: i * hold,
      op: (i + 1) * hold,
      shapes: frame.shapes,
      opacity: frame.opacity ?? 100,
    }),
  );
  return {
    v: "5.7.0",
    fr: fps,
    ip: 0,
    op,
    w,
    h,
    nm: name,
    ddd: 0,
    assets: [],
    layers,
    meta: { loop, g: generator },
  };
}

export function bake({ skin, pose, canvas, tolerance, model, shading, extras }) {
  const { parts } = buildFigure({
    skin,
    pose,
    tolerance,
    model,
    extras,
    shading: {
      ...(shading ?? { ...DEFAULT_SHADING, grade: false }),
      flash: pose.flash ?? shading?.flash ?? 0,
    },
  });
  const project = makeProjector({
    scale: canvas.scale,
    originX: canvas.originX,
    originY: canvas.originY,
    roll: pose.roll ?? canvas.roll ?? 0,
  });
  return { parts, project, shapes: figureToLottieShapes(parts, project) };
}

export function frameSvg({ generator, id, label, groupId, w, h, parts, project }) {
  return `<!-- Generated by ${generator} -->
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${w} ${h}" width="${w}" height="${h}" role="img" aria-labelledby="${id}-title">
  <title id="${id}-title">${label}</title>
  <g id="${groupId}">
${svgFigureBody(parts, project).join("\n")}
  </g>
</svg>
`;
}

export async function writeHeroSvg({ generator, out, title, desc, groupId, skin, pose, tolerance, model, canvas, shading }) {
  const { parts } = buildFigure({
    skin,
    pose,
    tolerance,
    model,
    shading: shading ?? { ...DEFAULT_SHADING, grade: false },
  });
  const project = fitProjector(parts, canvas, pose.roll ?? 0);
  const svg = `<!-- Generated by ${generator} — edit the pose library, not this file. -->
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${canvas.w} ${canvas.h}" width="${canvas.w}" height="${canvas.h}" role="img" aria-labelledby="${groupId}-title ${groupId}-desc">
  <title id="${groupId}-title">${title}</title>
  <desc id="${groupId}-desc">${desc}</desc>
  <g id="${groupId}">
${svgFigureBody(parts, project).join("\n")}
  </g>
</svg>
`;
  await mkdir(dirname(out), { recursive: true });
  await writeFile(out, svg);
  return svg;
}

export async function writeFrames({ generator, groupId, sprite, frames, outDir }) {
  await mkdir(outDir, { recursive: true });
  for (const frame of frames) {
    const svg = frameSvg({
      generator,
      id: frame.id,
      label: frame.label,
      groupId,
      w: sprite.w,
      h: sprite.h,
      parts: frame.parts,
      project: frame.project,
    });
    await writeFile(resolve(outDir, `${frame.id}.svg`), svg);
  }
}

// Bake sampled pose clips (idle / hurt / death) as individual SVG frames
// without rewriting the walk sheet.
export async function writeSampledClips({
  generator,
  groupId,
  sprite,
  outDir,
  skin,
  tolerance,
  model,
  sequences,
}) {
  const written = [];
  for (const seq of sequences) {
    const frames = Array.from({ length: seq.count }, (_, i) => {
      const t = seq.loop ? i / seq.count : i / Math.max(1, seq.count - 1);
      const baked = bake({ skin, pose: seq.sample(t), canvas: sprite, tolerance, model, extras: seq.extras });
      return { id: `${seq.prefix}-${i}`, label: `${seq.label} ${i + 1}/${seq.count}`, ...baked };
    });
    await writeFrames({ generator, groupId, sprite, frames, outDir });
    written.push(...frames);
  }
  return written;
}

export async function writeSpriteKit({
  generator,
  groupId,
  sprite,
  frames,
  outDir,
  stillPath,
  stillLabel,
  stillIndex,
}) {
  await mkdir(outDir, { recursive: true });
  const written = [];
  for (const frame of frames) {
    const svg = frameSvg({
      generator,
      id: frame.id,
      label: frame.label,
      groupId,
      w: sprite.w,
      h: sprite.h,
      parts: frame.parts,
      project: frame.project,
    });
    await writeFile(resolve(outDir, `${frame.id}.svg`), svg);
    written.push({ ...frame, bytes: svg.length });
  }
  const mid = written[stillIndex ?? Math.floor(written.length / 4)];
  await writeFile(
    stillPath,
    frameSvg({
      generator: `${generator} (${mid.id})`,
      id: `${groupId}-walk`,
      label: stillLabel,
      groupId,
      w: sprite.w,
      h: sprite.h,
      parts: mid.parts,
      project: mid.project,
    }),
  );
  const sheetW = written.length * sprite.w;
  const cells = [];
  written.forEach((frame, i) => {
    cells.push(`  <g id="${frame.id}" transform="translate(${i * sprite.w} 0)">`);
    cells.push(...svgFigureBody(frame.parts, frame.project, "    ", `${frame.id}-`));
    cells.push("  </g>");
  });
  await writeFile(
    resolve(outDir, "sheet.svg"),
    `<!-- Generated by ${generator} -->
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${sheetW} ${sprite.h}" width="${sheetW}" height="${sprite.h}" role="img" aria-label="${groupId} walk sprite sheet">
${cells.join("\n")}
</svg>
`,
  );
  return written;
}

export async function writeScene(dir, lottie) {
  await mkdir(dir, { recursive: true });
  for (const name of await readdir(dir).catch(() => [])) {
    if (name.endsWith(".svg")) await rm(resolve(dir, name));
  }
  await writeFile(resolve(dir, "lottie.json"), JSON.stringify(lottie) + "\n");
  const kb = (Buffer.byteLength(JSON.stringify(lottie)) / 1024).toFixed(1);
  console.log(
    `${dir.replace(`${ROOT}/`, "")}  ${lottie.nm}  ${lottie.layers.length} poses  ${lottie.op} ticks @ ${lottie.fr} fps  ${kb} kB`,
  );
}

export { ROOT };
