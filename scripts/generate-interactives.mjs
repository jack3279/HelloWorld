// Armor overlays on Steve (idle + run), open chest / door faces, fire
// flipbook, primed TNT, XP orb, shield icon.
//
// Usage: node scripts/generate-interactives.mjs
import { mkdir, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { armorLayer1Model, armorLeggingsExtras } from "./lib/armor-model.mjs";
import { CHEST_MODEL, SHIELD_MODEL } from "./lib/chest-model.mjs";
import {
  ALPHA_CUTOFF,
  SINGLE,
  TILE,
  layoutSingle,
  loadBlock,
  runsOf,
  svgFromRuns,
  wrapSvg,
} from "./lib/minecraft-blocks.mjs";
import { bake, writeHeroSvg } from "./lib/mob-pipeline.mjs";
import {
  DEFAULT_SHADING,
  buildFigure,
  decodeTexture,
  loadArmorLayer,
  loadChestSkin,
  loadShieldSkin,
  makeProjector,
  svgFigureBody,
} from "./lib/steve-model.mjs";
import { SPRITE, TOLERANCE, idleA, runFrame } from "./lib/steve-poses.mjs";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, "..");
const ARMOR_KINDS = ["leather", "iron", "diamond", "gold", "chainmail", "netherite"];

function frameSvg(generator, id, label, groupId, canvas, parts, project) {
  return `<!-- Generated by ${generator} -->
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${canvas.w} ${canvas.h}" width="${canvas.w}" height="${canvas.h}" role="img" aria-labelledby="${id}-title">
  <title id="${id}-title">${label}</title>
  <g id="${groupId}">
${svgFigureBody(parts, project).join("\n")}
  </g>
</svg>
`;
}

async function bakeArmor(kind, pose) {
  const layer1 = await loadArmorLayer(kind, 1);
  const layer2 = await loadArmorLayer(kind, 2);
  const extras = armorLeggingsExtras().map((part) => ({ part, skin: layer2, tolerance: { default: 10 } }));
  const { parts } = buildFigure({
    skin: layer1,
    pose,
    tolerance: TOLERANCE,
    model: armorLayer1Model(),
    extras,
    shading: { ...DEFAULT_SHADING, grade: false },
  });
  const project = makeProjector({
    scale: SPRITE.scale,
    originX: SPRITE.originX,
    originY: SPRITE.originY,
  });
  return { parts, project };
}

async function writeArmorOverlays() {
  const outDir = resolve(ROOT, "assets/steve-sprites");
  await mkdir(outDir, { recursive: true });
  for (const kind of ARMOR_KINDS) {
    const idle = await bakeArmor(kind, idleA());
    await writeFile(
      resolve(outDir, `armor-${kind}.svg`),
      frameSvg("scripts/generate-interactives.mjs", `armor-${kind}`, `${kind} armor overlay`, `armor-${kind}`, SPRITE, idle.parts, idle.project),
    );
    for (let i = 0; i < 8; i++) {
      const run = await bakeArmor(kind, runFrame(i / 8));
      await writeFile(
        resolve(outDir, `armor-${kind}-run-${i}.svg`),
        frameSvg(
          "scripts/generate-interactives.mjs",
          `armor-${kind}-run-${i}`,
          `${kind} armor run ${i + 1}/8`,
          `armor-${kind}-run-${i}`,
          SPRITE,
          run.parts,
          run.project,
        ),
      );
    }
    console.log(`Wrote armor overlays for ${kind}`);
  }
}

async function writeChestOpen() {
  const skin = await loadChestSkin();
  const open = { view: { yaw: 42, pitch: -8 }, root: {}, parts: { lid: { pitch: -110 }, latch: {} } };
  await writeHeroSvg({
    generator: "scripts/generate-interactives.mjs",
    out: resolve(ROOT, "assets/blocks/chest-open.svg"),
    title: "Chest, open",
    desc: "Voxel chest from the entity sheet with the lid rotated open. Bedrock has no 16×16 open-chest face.",
    groupId: "chest-open",
    skin,
    pose: open,
    tolerance: { default: 12 },
    model: CHEST_MODEL,
    canvas: { w: 512, h: 512, pad: 48 },
  });
  console.log("Wrote assets/blocks/chest-open.svg");
}

function hingeDoor(png, cols = 3) {
  const rgba = new Uint8Array(TILE * TILE * 4);
  for (let y = 0; y < TILE; y++) {
    for (let x = 0; x < cols; x++) {
      const si = (y * png.width + x) * 4;
      const di = (y * TILE + x) * 4;
      rgba[di] = png.rgba[si];
      rgba[di + 1] = png.rgba[si + 1];
      rgba[di + 2] = png.rgba[si + 2];
      rgba[di + 3] = png.rgba[si + 3] < ALPHA_CUTOFF ? 0 : 255;
    }
    const edge = cols;
    if (edge < TILE) {
      const si = (y * png.width + Math.min(cols - 1, png.width - 1)) * 4;
      const di = (y * TILE + edge) * 4;
      rgba[di] = Math.max(0, png.rgba[si] - 28);
      rgba[di + 1] = Math.max(0, png.rgba[si + 1] - 28);
      rgba[di + 2] = Math.max(0, png.rgba[si + 2] - 28);
      rgba[di + 3] = png.rgba[si + 3] < ALPHA_CUTOFF ? 0 : 255;
    }
  }
  return { width: TILE, height: TILE, rgba };
}

async function writeOpenDoors() {
  const outDir = resolve(ROOT, "assets/blocks");
  const box = layoutSingle();
  for (const [id, src, title] of [
    ["door-oak-open", "door-oak", "橡木门（开）"],
    ["door-oak-upper-open", "door-oak-upper", "橡木门上（开）"],
  ]) {
    const png = hingeDoor(await loadBlock(src));
    const svg = wrapSvg(
      id,
      `${title} / Open oak door`,
      SINGLE,
      `<g id="${id}">\n    ${svgFromRuns(runsOf(png), box).join("\n    ")}\n  </g>`,
    ).replace("generate-blocks-svg.mjs", "generate-interactives.mjs");
    await writeFile(resolve(outDir, `${id}.svg`), svg);
    console.log(`Wrote assets/blocks/${id}.svg`);
  }
}

function cropFace(png, sx, sy) {
  const rgba = new Uint8Array(TILE * TILE * 4);
  for (let y = 0; y < TILE; y++) {
    for (let x = 0; x < TILE; x++) {
      const si = ((sy + y) * png.width + (sx + x)) * 4;
      const di = (y * TILE + x) * 4;
      if (sx + x < png.width && sy + y < png.height) rgba.set(png.rgba.subarray(si, si + 4), di);
    }
  }
  return { width: TILE, height: TILE, rgba };
}

async function writeFire() {
  const url = "https://raw.githubusercontent.com/Mojang/bedrock-samples/main/resource_pack/textures/blocks/fire_0.png";
  const res = await fetch(url);
  if (!res.ok) throw new Error(`could not download fire_0.png (${res.status})`);
  const png = decodeTexture(Buffer.from(await res.arrayBuffer()));
  const frames = Math.max(1, Math.floor(png.height / TILE));
  const box = layoutSingle();
  const pick = [];
  for (let i = 0; i < 8; i++) pick.push(Math.floor((i * frames) / 8) % frames);
  for (let i = 0; i < pick.length; i++) {
    const cropped = cropFace(png, 0, pick[i] * TILE);
    const id = i === 0 ? "fire" : `fire-${i}`;
    const svg = wrapSvg(
      id,
      `火焰 / Fire ${i + 1}/8`,
      SINGLE,
      `<g id="${id}">\n    ${svgFromRuns(runsOf(cropped), box).join("\n    ")}\n  </g>`,
    ).replace("generate-blocks-svg.mjs", "generate-interactives.mjs");
    await writeFile(resolve(ROOT, "assets/blocks", `${id}.svg`), svg);
  }
  console.log("Wrote assets/blocks/fire.svg plus fire-1..7");
}

async function writeTntPrimed() {
  const png = await loadBlock("tnt");
  const rgba = new Uint8Array(png.rgba);
  for (let i = 0; i < rgba.length; i += 4) {
    if (rgba[i + 3] < ALPHA_CUTOFF) continue;
    rgba[i] = Math.min(255, rgba[i] + 70);
    rgba[i + 1] = Math.min(255, rgba[i + 1] + 70);
    rgba[i + 2] = Math.min(255, rgba[i + 2] + 40);
  }
  const box = layoutSingle();
  const svg = wrapSvg(
    "tnt-primed",
    "点燃的 TNT / Primed TNT",
    SINGLE,
    `<g id="tnt-primed">\n    ${svgFromRuns(runsOf({ ...png, rgba }), box).join("\n    ")}\n  </g>`,
  ).replace("generate-blocks-svg.mjs", "generate-interactives.mjs");
  await writeFile(resolve(ROOT, "assets/blocks/tnt-primed.svg"), svg);
  console.log("Wrote assets/blocks/tnt-primed.svg");
}

async function writeXpOrb() {
  const url = "https://raw.githubusercontent.com/Mojang/bedrock-samples/main/resource_pack/textures/entity/experience_orb.png";
  const res = await fetch(url);
  if (!res.ok) throw new Error(`could not download experience_orb.png (${res.status})`);
  const png = decodeTexture(Buffer.from(await res.arrayBuffer()));
  const cropped = cropFace(png, 0, 0);
  const rgba = new Uint8Array(cropped.rgba);
  for (let i = 0; i < rgba.length; i += 4) {
    if (rgba[i + 3] < ALPHA_CUTOFF) continue;
    const y = Math.max(rgba[i], rgba[i + 1], rgba[i + 2]);
    rgba[i] = Math.round(y * 0.5);
    rgba[i + 1] = Math.round(y * 0.95);
    rgba[i + 2] = Math.round(y * 0.18);
  }
  const box = layoutSingle();
  const svg = wrapSvg(
    "xp-orb",
    "经验球 / Experience orb",
    SINGLE,
    `<g id="xp-orb">\n    ${svgFromRuns(runsOf({ width: TILE, height: TILE, rgba }), box).join("\n    ")}\n  </g>`,
  ).replace("generate-blocks-svg.mjs", "generate-interactives.mjs");
  await writeFile(resolve(ROOT, "assets/items/xp-orb.svg"), svg);
  console.log("Wrote assets/items/xp-orb.svg");
}

async function writeShieldItem() {
  const skin = await loadShieldSkin();
  const pose = { view: { yaw: 38, pitch: -6 }, root: {}, parts: { plate: {}, handle: {} } };
  const baked = bake({
    skin,
    pose,
    canvas: { w: 512, h: 512, scale: 16, originX: 256, originY: 400 },
    tolerance: { default: 10 },
    model: SHIELD_MODEL,
  });
  const svg = frameSvg(
    "scripts/generate-interactives.mjs",
    "shield",
    "盾 / Shield",
    "shield",
    { w: 512, h: 512 },
    baked.parts,
    baked.project,
  );
  await writeFile(resolve(ROOT, "assets/items/shield.svg"), svg);
  console.log("Wrote assets/items/shield.svg");
}

await writeArmorOverlays();
await writeChestOpen();
await writeOpenDoors();
await writeFire();
await writeTntPrimed();
await writeXpOrb();
await writeShieldItem();
