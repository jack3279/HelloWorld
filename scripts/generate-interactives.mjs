// Armor overlays on idle Steve, open chest / door faces, fire tile, shield icon.
//
// Usage: node scripts/generate-interactives.mjs
import { mkdir, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { armorLayer1Model, armorLeggingsExtras } from "./lib/armor-model.mjs";
import { CHEST_MODEL, SHIELD_MODEL } from "./lib/chest-model.mjs";
import {
  ALPHA_CUTOFF,
  SINGLE,
  TILE,
  layoutSingle,
  loadBlock,
  runsOf,
  svgFromRuns,
  wrapSvg,
} from "./lib/minecraft-blocks.mjs";
import { bake, writeHeroSvg } from "./lib/mob-pipeline.mjs";
import {
  DEFAULT_SHADING,
  buildFigure,
  decodeTexture,
  loadArmorLayer,
  loadChestSkin,
  loadShieldSkin,
  makeProjector,
  svgFigureBody,
} from "./lib/steve-model.mjs";
import { SPRITE, TOLERANCE, idleA } from "./lib/steve-poses.mjs";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, "..");

function frameSvg(generator, id, label, groupId, canvas, parts, project) {
  return `<!-- Generated by ${generator} -->
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${canvas.w} ${canvas.h}" width="${canvas.w}" height="${canvas.h}" role="img" aria-labelledby="${id}-title">
  <title id="${id}-title">${label}</title>
  <g id="${groupId}">
${svgFigureBody(parts, project).join("\n")}
  </g>
</svg>
`;
}

async function writeArmorOverlays() {
  const outDir = resolve(ROOT, "assets/steve-sprites");
  await mkdir(outDir, { recursive: true });
  const model = armorLayer1Model();
  const pose = idleA();
  for (const kind of ["leather", "iron", "diamond"]) {
    const layer1 = await loadArmorLayer(kind, 1);
    const layer2 = await loadArmorLayer(kind, 2);
    const extras = armorLeggingsExtras().map((part) => ({ part, skin: layer2, tolerance: { default: 10 } }));
    const { parts } = buildFigure({
      skin: layer1,
      pose,
      tolerance: TOLERANCE,
      model,
      extras,
      shading: { ...DEFAULT_SHADING, grade: false },
    });
    const project = makeProjector({
      scale: SPRITE.scale,
      originX: SPRITE.originX,
      originY: SPRITE.originY,
    });
    const svg = frameSvg(
      "scripts/generate-interactives.mjs",
      `armor-${kind}`,
      `${kind} armor overlay`,
      `armor-${kind}`,
      SPRITE,
      parts,
      project,
    );
    const out = resolve(outDir, `armor-${kind}.svg`);
    await writeFile(out, svg);
    console.log(`Wrote ${out}`);
  }
}

async function writeChestOpen() {
  const skin = await loadChestSkin();
  const open = { view: { yaw: 42, pitch: -8 }, root: {}, parts: { lid: { pitch: -110 }, latch: {} } };
  await writeHeroSvg({
    generator: "scripts/generate-interactives.mjs",
    out: resolve(ROOT, "assets/blocks/chest-open.svg"),
    title: "Chest, open",
    desc: "Voxel chest from the entity sheet with the lid rotated open. Bedrock has no 16×16 open-chest face.",
    groupId: "chest-open",
    skin,
    pose: open,
    tolerance: { default: 12 },
    model: CHEST_MODEL,
    canvas: { w: 512, h: 512, pad: 48 },
  });
  console.log("Wrote assets/blocks/chest-open.svg");
}

function hingeDoor(png, cols = 3) {
  const rgba = new Uint8Array(TILE * TILE * 4);
  for (let y = 0; y < TILE; y++) {
    for (let x = 0; x < cols; x++) {
      const si = (y * png.width + x) * 4;
      const di = (y * TILE + x) * 4;
      rgba[di] = png.rgba[si];
      rgba[di + 1] = png.rgba[si + 1];
      rgba[di + 2] = png.rgba[si + 2];
      rgba[di + 3] = png.rgba[si + 3] < ALPHA_CUTOFF ? 0 : 255;
    }
    const edge = cols;
    if (edge < TILE) {
      const si = (y * png.width + Math.min(cols - 1, png.width - 1)) * 4;
      const di = (y * TILE + edge) * 4;
      rgba[di] = Math.max(0, png.rgba[si] - 28);
      rgba[di + 1] = Math.max(0, png.rgba[si + 1] - 28);
      rgba[di + 2] = Math.max(0, png.rgba[si + 2] - 28);
      rgba[di + 3] = png.rgba[si + 3] < ALPHA_CUTOFF ? 0 : 255;
    }
  }
  return { width: TILE, height: TILE, rgba };
}

async function writeOpenDoors() {
  const outDir = resolve(ROOT, "assets/blocks");
  const box = layoutSingle();
  for (const [id, src, title] of [
    ["door-oak-open", "door-oak", "橡木门（开）"],
    ["door-oak-upper-open", "door-oak-upper", "橡木门上（开）"],
  ]) {
    const png = hingeDoor(await loadBlock(src));
    const svg = wrapSvg(
      id,
      `${title} / Open oak door`,
      SINGLE,
      `<g id="${id}">\n    ${svgFromRuns(runsOf(png), box).join("\n    ")}\n  </g>`,
    ).replace("generate-blocks-svg.mjs", "generate-interactives.mjs");
    await writeFile(resolve(outDir, `${id}.svg`), svg);
    console.log(`Wrote assets/blocks/${id}.svg`);
  }
}

async function writeFire() {
  const url = "https://raw.githubusercontent.com/Mojang/bedrock-samples/main/resource_pack/textures/blocks/fire_0.png";
  const res = await fetch(url);
  if (!res.ok) throw new Error(`could not download fire_0.png (${res.status})`);
  const png = decodeTexture(Buffer.from(await res.arrayBuffer()));
  const cropped = { width: TILE, height: TILE, rgba: new Uint8Array(TILE * TILE * 4) };
  for (let y = 0; y < TILE; y++) {
    for (let x = 0; x < TILE; x++) {
      const sy = Math.min(png.height - 1, y + Math.max(0, png.height - TILE));
      const si = (sy * png.width + x) * 4;
      const di = (y * TILE + x) * 4;
      cropped.rgba.set(png.rgba.subarray(si, si + 4), di);
    }
  }
  const box = layoutSingle();
  const svg = wrapSvg(
    "fire",
    "火焰 / Fire",
    SINGLE,
    `<g id="fire">\n    ${svgFromRuns(runsOf(cropped), box).join("\n    ")}\n  </g>`,
  ).replace("generate-blocks-svg.mjs", "generate-interactives.mjs");
  await writeFile(resolve(ROOT, "assets/blocks/fire.svg"), svg);
  console.log("Wrote assets/blocks/fire.svg");
}

async function writeShieldItem() {
  const skin = await loadShieldSkin();
  const pose = { view: { yaw: 38, pitch: -6 }, root: {}, parts: { plate: {}, handle: {} } };
  const baked = bake({
    skin,
    pose,
    canvas: { w: 512, h: 512, scale: 16, originX: 256, originY: 400 },
    tolerance: { default: 10 },
    model: SHIELD_MODEL,
  });
  const svg = frameSvg(
    "scripts/generate-interactives.mjs",
    "shield",
    "盾 / Shield",
    "shield",
    { w: 512, h: 512 },
    baked.parts,
    baked.project,
  );
  await writeFile(resolve(ROOT, "assets/items/shield.svg"), svg);
  console.log("Wrote assets/items/shield.svg");
}

await writeArmorOverlays();
await writeChestOpen();
await writeOpenDoors();
await writeFire();
await writeShieldItem();
