// Generates assets/steve.svg: the hero pose, a three-quarter view of the player
// model mid-stride with one arm thrust forward.
//
// Usage:
//   node scripts/generate-steve-svg.mjs [--skin=<png>] [--out=<svg>]
//
// Geometry, texturing and shading live in lib/steve-model.mjs; this file only
// owns the pose and the canvas.
import { mkdir, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { buildFigure, fitProjector, loadSkin, parseArgs, svgFigureBody } from "./lib/steve-model.mjs";

const __dirname = dirname(fileURLToPath(import.meta.url));

const CANVAS = { w: 512, h: 560, pad: 14 };

// Angles in degrees. Negative limb pitch swings forward, positive swings back.
const POSE = {
  view: { yaw: -34, pitch: 19 }, // three-quarter turn, camera slightly above
  roll: 8, // screen-space lean into the run
  parts: {
    torso: { pitch: -4 },
    head: { yaw: 16, pitch: -2, roll: -6 },
    "arm-right": { yaw: -6, pitch: -104, roll: 7 },
    "arm-left": { yaw: 4, pitch: 38, roll: -13 },
    "leg-right": { pitch: -38, roll: 4 },
    "leg-left": { pitch: 27, roll: -4 },
  },
};

// The head keeps a tight tolerance so brows, eyes, mustache and beard survive;
// the rest of the body is flattened harder to kill the skin's dither noise.
const TOLERANCE = { default: 30, head: 12 };

const args = parseArgs(process.argv.slice(2));
const skin = await loadSkin(args.get("skin"));
if (skin.width < 64 || skin.height < 64) throw new Error("expected a 64x64 skin");

const { parts, palette } = buildFigure({ skin, pose: POSE, tolerance: TOLERANCE });
const project = fitProjector(parts, CANVAS, POSE.roll);
const svg = `<!-- Generated by scripts/generate-steve-svg.mjs — edit the pose there, not here. -->
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${CANVAS.w} ${CANVAS.h}" width="${CANVAS.w}" height="${CANVAS.h}" role="img" aria-labelledby="steve-title steve-desc">
  <title id="steve-title">Steve, mid-stride</title>
  <desc id="steve-desc">Voxel character running with one arm thrust forward, drawn face by face from the classic player skin.</desc>
  <g id="steve">
${svgFigureBody(parts, project).join("\n")}
  </g>
</svg>
`;

const out = resolve(__dirname, "..", args.get("out") ?? "assets/steve.svg");
await mkdir(dirname(out), { recursive: true });
await writeFile(out, svg);
console.log(
  `Wrote ${out} (${(svg.length / 1024).toFixed(1)} kB, ${palette.size} flat colors, ` +
    `${parts.reduce((n, p) => n + p.faces.length, 0)} visible faces)`,
);
