// Generates assets/creeper-side.svg: a right-facing Minecraft creeper.
// The body stays in true profile; the head turns 45° toward the camera so
// both eyes and the frown read on the front of the cube.
//
// Usage:
//   node scripts/generate-creeper-svg.mjs [--skin=<png>] [--out=<svg>]
import { mkdir, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { buildFigure, fitProjector, loadCreeperSkin, parseArgs, svgFigureBody } from "./lib/steve-model.mjs";
import { CREEPER_MODEL } from "./lib/creeper-model.mjs";
import { idleA, TOLERANCE } from "./lib/creeper-poses.mjs";

const __dirname = dirname(fileURLToPath(import.meta.url));

const CANVAS = { w: 512, h: 480, pad: 20 };

const args = parseArgs(process.argv.slice(2));
const skin = await loadCreeperSkin(args.get("skin"));
if (skin.width < 64 || skin.height < 32) throw new Error("expected a 64x32 creeper texture");

const pose = idleA();
const { parts, palette } = buildFigure({ skin, pose, tolerance: TOLERANCE, model: CREEPER_MODEL });
const project = fitProjector(parts, CANVAS, pose.roll ?? 0);
const svg = `<!-- Generated by scripts/generate-creeper-svg.mjs — edit the pose in lib/creeper-poses.mjs, not here. -->
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${CANVAS.w} ${CANVAS.h}" width="${CANVAS.w}" height="${CANVAS.h}" role="img" aria-labelledby="creeper-title creeper-desc">
  <title id="creeper-title">Creeper, side view</title>
  <desc id="creeper-desc">Voxel creeper facing right with the head turned 45 degrees so the face — both eyes and the frown — stays readable. Four legs, no arms.</desc>
  <g id="creeper">
${svgFigureBody(parts, project).join("\n")}
  </g>
</svg>
`;

const out = resolve(__dirname, "..", args.get("out") ?? "assets/creeper-side.svg");
await mkdir(dirname(out), { recursive: true });
await writeFile(out, svg);
console.log(
  `Wrote ${out} (${(svg.length / 1024).toFixed(1)} kB, ${palette.size} flat colors, ` +
    `${parts.reduce((n, p) => n + p.faces.length, 0)} visible faces)`,
);
