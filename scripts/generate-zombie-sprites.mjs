// Generates the side-view zombie walk kit:
//   assets/zombie-walk.svg             mid-stride still, facing right
//   assets/zombie-sprites/walk-N.svg   one frame per pose
//   assets/zombie-sprites/sheet.svg    all walk frames in a row
//
// Usage:
//   node scripts/generate-zombie-sprites.mjs [--skin=<png>] [--out=<dir>]
import { mkdir, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { buildFigure, loadZombieSkin, makeProjector, parseArgs, svgFigureBody } from "./lib/steve-model.mjs";
import { SPRITE, TOLERANCE, catalog } from "./lib/zombie-poses.mjs";

const __dirname = dirname(fileURLToPath(import.meta.url));

const project = makeProjector({
  scale: SPRITE.scale,
  originX: SPRITE.originX,
  originY: SPRITE.originY,
});

function frameSvg(id, label, parts) {
  return `<!-- Generated by scripts/generate-zombie-sprites.mjs -->
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${SPRITE.w} ${SPRITE.h}" width="${SPRITE.w}" height="${SPRITE.h}" role="img" aria-labelledby="${id}-title">
  <title id="${id}-title">${label}</title>
  <g id="zombie">
${svgFigureBody(parts, project).join("\n")}
  </g>
</svg>
`;
}

const args = parseArgs(process.argv.slice(2));
const skin = await loadZombieSkin(args.get("skin"));
if (skin.width < 64 || skin.height < 64) throw new Error("expected a 64x64 skin");

const outDir = resolve(__dirname, "..", args.get("out") ?? "assets/zombie-sprites");
await mkdir(outDir, { recursive: true });

const frames = [];
for (const entry of catalog()) {
  const { parts } = buildFigure({ skin, pose: entry.pose, tolerance: TOLERANCE });
  const svg = frameSvg(entry.id, entry.label, parts);
  await writeFile(resolve(outDir, `${entry.id}.svg`), svg);
  frames.push({ ...entry, parts, bytes: svg.length });
}

const mid = frames[Math.floor(frames.length / 4)];
const walkStill = resolve(__dirname, "../assets/zombie-walk.svg");
await writeFile(
  walkStill,
  frameSvg("zombie-walk", "Zombie, walking, facing right", mid.parts).replace(
    "generate-zombie-sprites.mjs",
    "generate-zombie-sprites.mjs (walk-4)",
  ),
);

const sheetW = frames.length * SPRITE.w;
const sheetH = SPRITE.h;
const cells = [];
frames.forEach((frame, i) => {
  const x = i * SPRITE.w;
  cells.push(`  <g id="${frame.id}" transform="translate(${x} 0)">`);
  cells.push(...svgFigureBody(frame.parts, project, "    ", `${frame.id}-`));
  cells.push("  </g>");
});

await writeFile(
  resolve(outDir, "sheet.svg"),
  `<!-- Generated by scripts/generate-zombie-sprites.mjs -->
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${sheetW} ${sheetH}" width="${sheetW}" height="${sheetH}" role="img" aria-label="Zombie walk sprite sheet">
${cells.join("\n")}
</svg>
`,
);

const kb = (n) => (n / 1024).toFixed(1);
console.log(
  `Wrote ${frames.length} walk frames in ${outDir} (${kb(frames.reduce((n, f) => n + f.bytes, 0))} kB) plus sheet.svg`,
);
console.log(`Wrote ${walkStill}`);
