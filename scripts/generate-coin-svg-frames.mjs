// Bake the spinning coin into a quarter-rate SVG sequence.
//
// Uses the same poseAt() math as the Lottie. Every 4th Lottie tick
// (0, 4, …, 88) becomes one static SVG — 23 frames, 15 fps if played in order.
//
//   assets/coin-frames/coin-00.svg … coin-88.svg
//   assets/coin-frames/sheet.svg
//   assets/coin-frames/atlas.json
//
// Usage: node scripts/generate-coin-svg-frames.mjs
import { mkdir, readdir, rm, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import {
  BACK,
  BACK_DOT,
  BACK_WELL,
  CX,
  CY,
  EDGE_R,
  GOLD,
  GOLD_LINE,
  GOLD_MID,
  H,
  OP,
  STAR,
  T,
  W,
  WELL,
  poseAt,
  starVertices,
} from "./generate-coin-lottie.mjs";

const __dirname = dirname(fileURLToPath(import.meta.url));

export const SVG_STEP = 4;
export const SVG_DIR = "assets/coin-frames";

export function svgFrameNumbers(op = OP, step = SVG_STEP) {
  const frames = [];
  for (let f = 0; f < op; f += step) frames.push(f);
  return frames;
}

const fmt = (n) => {
  const r = Math.round(n * 100) / 100;
  return Object.is(r, -0) ? "0" : String(r);
};

const hex = (c) =>
  `#${c
    .slice(0, 3)
    .map((ch) => Math.round(ch * 255).toString(16).padStart(2, "0"))
    .join("")}`;

const GOLD_HEX = hex(GOLD);
const GOLD_MID_HEX = hex(GOLD_MID);
const GOLD_LINE_HEX = hex(GOLD_LINE);
const WELL_HEX = hex(WELL);
const STAR_HEX = hex(STAR);
const BACK_HEX = hex(BACK);
const BACK_WELL_HEX = hex(BACK_WELL);
const BACK_DOT_HEX = hex(BACK_DOT);

function attr(stroke, width) {
  if (!stroke) return "";
  return ` stroke="${stroke}" stroke-width="${width}" stroke-linecap="round" stroke-linejoin="round"`;
}

function ellipse(w, h, fill, stroke, sw) {
  return `    <ellipse cx="0" cy="0" rx="${fmt(w / 2)}" ry="${fmt(h / 2)}" fill="${fill}"${attr(stroke, sw)}/>`;
}

function roundRect(w, h, r, fill, stroke, sw) {
  return `    <rect x="${fmt(-w / 2)}" y="${fmt(-h / 2)}" width="${fmt(w)}" height="${fmt(h)}" rx="${fmt(r)}" ry="${fmt(r)}" fill="${fill}"${attr(stroke, sw)}/>`;
}

function starPoly() {
  const pts = starVertices(30, 13)
    .map(([x, y]) => `${fmt(x)},${fmt(y)}`)
    .join(" ");
  return `    <polygon points="${pts}" fill="${STAR_HEX}"${attr(GOLD_LINE_HEX, 1.5)}/>`;
}

function faceGroup(id, x, sx, opacity, inner) {
  if (opacity <= 0) return "";
  const o = opacity < 99.5 ? ` opacity="${fmt(opacity / 100)}"` : "";
  return `  <g id="${id}" transform="translate(${fmt(x)} ${CY}) scale(${fmt(sx / 100)} 1)"${o}>\n${inner}\n  </g>`;
}

export function coinSvg(frame) {
  const p = poseAt(frame);
  const edgeW = Math.max(p.bodyW, T * 0.85);
  const parts = [
    `  <g id="rim" transform="translate(${CX} ${CY})">`,
    roundRect(p.bodyW, 2 * 100, p.bodyR, GOLD_MID_HEX, GOLD_LINE_HEX, 1.6),
    `  </g>`,
  ];
  if (p.edgeO > 0) {
    parts.push(
      `  <g id="edge" transform="translate(${CX} ${CY})" opacity="${fmt(p.edgeO / 100)}">`,
      roundRect(edgeW, 2 * 100, EDGE_R, GOLD_MID_HEX, GOLD_LINE_HEX, 1.2),
      `  </g>`,
    );
  }
  const back = faceGroup(
    "back",
    p.backX,
    p.faceSx,
    p.backO,
    [
      ellipse(200, 200, GOLD_MID_HEX),
      ellipse(160, 160, BACK_HEX, GOLD_LINE_HEX, 4),
      ellipse(110, 110, BACK_WELL_HEX, GOLD_LINE_HEX, 2),
      ellipse(22, 22, BACK_DOT_HEX),
    ].join("\n"),
  );
  const front = faceGroup(
    "front",
    p.frontX,
    p.faceSx,
    p.frontO,
    [
      ellipse(200, 200, GOLD_MID_HEX),
      ellipse(164, 164, GOLD_HEX, GOLD_LINE_HEX, 5),
      ellipse(118, 118, WELL_HEX, GOLD_LINE_HEX, 3),
      starPoly(),
    ].join("\n"),
  );
  if (back) parts.push(back);
  if (front) parts.push(front);

  return `<!-- Generated by scripts/generate-coin-svg-frames.mjs from Lottie frame ${frame} -->
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${W} ${H}" width="${W}" height="${H}" role="img" aria-label="Gold coin frame ${frame}">
${parts.join("\n")}
</svg>
`;
}

export function frameFileName(frame) {
  return `coin-${String(frame).padStart(2, "0")}.svg`;
}

const isMain = String(process.argv[1] || "").endsWith("generate-coin-svg-frames.mjs");
if (isMain) {
  const outDir = resolve(__dirname, "..", SVG_DIR);
  await mkdir(outDir, { recursive: true });
  for (const name of await readdir(outDir)) {
    if (name.endsWith(".svg") || name === "atlas.json") await rm(resolve(outDir, name));
  }

  const frames = svgFrameNumbers();
  const atlasFrames = {};
  const cells = [];
  const COLS = 8;
  const ROWS = Math.ceil(frames.length / COLS);

  for (const [i, frame] of frames.entries()) {
    const svg = coinSvg(frame);
    const file = frameFileName(frame);
    await writeFile(resolve(outDir, file), svg);
    const col = i % COLS;
    const row = Math.floor(i / COLS);
    const inner = coinSvg(frame)
      .replace(/^<!--[\s\S]*?-->\n/, "")
      .replace(/^<svg[^>]*>\n/, "")
      .replace(/\n<\/svg>\n?$/, "")
      .split("\n")
      .map((line) => `    ${line}`)
      .join("\n");
    cells.push(`  <g id="cell-${file.replace(".svg", "")}" transform="translate(${col * W} ${row * H})">\n${inner}\n  </g>`);
    atlasFrames[file.replace(".svg", "")] = {
      file,
      lottieFrame: frame,
      degrees: Math.round((frame / OP) * 360 * 10) / 10,
    };
  }

  const sheet = `<!-- Generated by scripts/generate-coin-svg-frames.mjs -->
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${COLS * W} ${ROWS * H}" width="${COLS * W}" height="${ROWS * H}" role="img" aria-label="Gold coin SVG sequence, every ${SVG_STEP} frames">
${cells.join("\n")}
</svg>
`;
  await writeFile(resolve(outDir, "sheet.svg"), sheet);
  await writeFile(
    resolve(outDir, "atlas.json"),
    JSON.stringify(
      {
        meta: {
          source: "scripts/generate-coin-lottie.mjs poseAt",
          step: SVG_STEP,
          lottieFps: 60,
          sequenceFps: 60 / SVG_STEP,
          size: { w: W, h: H },
          count: frames.length,
        },
        frames: atlasFrames,
      },
      null,
      2,
    ) + "\n",
  );
  console.log(`Wrote ${frames.length} SVG frames + sheet to ${outDir}`);
}
