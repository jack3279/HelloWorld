// Off-hand 3D shield overlays parented to Steve's left arm.
// Usage: node scripts/generate-shield-hold.mjs
import { mkdir, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { shieldExtras } from "./lib/held-item.mjs";
import { bake } from "./lib/mob-pipeline.mjs";
import { loadSkin, svgFigureBody } from "./lib/steve-model.mjs";
import { SPRITE, TOLERANCE, idleA, runFrame } from "./lib/steve-poses.mjs";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, "..");

function frameSvg(id, label, parts, project) {
  return `<!-- Generated by scripts/generate-shield-hold.mjs -->
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${SPRITE.w} ${SPRITE.h}" width="${SPRITE.w}" height="${SPRITE.h}" role="img" aria-labelledby="${id}-title">
  <title id="${id}-title">${label}</title>
  <g id="${id}">
${svgFigureBody(parts, project).join("\n")}
  </g>
</svg>
`;
}

function shieldOverlayPose(base, armLeft = {}) {
  return {
    ...base,
    parts: {
      ...base.parts,
      "arm-left": { ...base.parts["arm-left"], ...armLeft },
    },
  };
}

const steve = await loadSkin();
const extras = await shieldExtras();
const outDir = resolve(ROOT, "assets/steve-sprites");
await mkdir(outDir, { recursive: true });

async function writeOverlay(id, label, pose) {
  const baked = bake({
    skin: steve,
    pose,
    canvas: SPRITE,
    tolerance: TOLERANCE,
    extras,
  });
  const parts = baked.parts.filter((p) => p.id === "shield-plate" || p.id === "shield-handle");
  await writeFile(resolve(outDir, `${id}.svg`), frameSvg(id, label, parts, baked.project));
}

await writeOverlay("shield-hold", "盾（副手持握） / Off-hand shield", shieldOverlayPose(idleA()));
await writeOverlay("shield-block", "盾（格挡） / Blocking shield", shieldOverlayPose(idleA(), { pitch: -88, yaw: 10 }));
for (let i = 0; i < 8; i++) {
  await writeOverlay(
    `shield-hold-run-${i}`,
    `盾奔跑 ${i + 1}/8 / Off-hand shield run ${i + 1}/8`,
    shieldOverlayPose(runFrame(i / 8)),
  );
}
console.log("Wrote off-hand shield overlays");
